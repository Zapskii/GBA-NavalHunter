static void put(int x, int y, uint8_t c)
{
    volatile uint16_t *p = gfx_fb + y * GFX_W / 2 + x / 2;
    *p = x & 1 ? (*p & 0x00FF) | c << 8 : (*p & 0xFF00) | c;
}

void gfx_rect(int x, int y, int w, int h, uint8_t c)
{
    int end = x + w;
    uint16_t two = c | c << 8;
    if (w <= 0) return;
    for (; h > 0; h--, y++) {
        int i = x;
        if (i & 1) put(i++, y, c);
        for (; i + 1 < end; i += 2) gfx_fb[y * GFX_W / 2 + i / 2] = two;
        if (i < end) put(i, y, c);
    }
}

void gfx_text(int x, int y, const char *s, uint8_t c)
{
    for (; *s; s++, x += 6) {
        int r, b;
        if (*s < ' ' || *s > ']') continue;
        for (r = 0; r < 7; r++)
            for (b = 0; b < 5; b++)
                if (font[*s - ' '][r] & 16 >> b) put(x + b, y + r, c);
    }
}
